def extract_robust_asset(text_fixed, text_clean_fixed, keyword_pattern, keyword_pattern_clean, exclude_str=None):
    best_asset = '未识别到编号'
    min_dist = 999999
    exclude_str = exclude_str.upper() if exclude_str else None

    for kw_match in re.finditer(keyword_pattern_clean, text_clean_fixed, re.IGNORECASE):
        kw_center = (kw_match.start() + kw_match.end()) // 2
        start = max(0, kw_match.start() - 200)
        end = min(len(text_clean_fixed), kw_match.end() + 300)
        window = text_clean_fixed[start:end]

        for p_match in re.finditer(ASSET_PATTERN, window):
            p = p_match.group(0)
            if len(p) >= 4:
                filtered = filter_asset_no(p)
                if filtered != '未识别到编号':
                    if exclude_str and (filtered == exclude_str or filtered in exclude_str):
                        continue

                    p_center = start + p_match.start() + len(p)//2
                    dist = abs(p_center - kw_center)
                    if re.match(r'^(H|WSJ|NDJ|WJ|A|B)\d+', filtered, re.IGNORECASE):
                        dist -= 10000
                    if dist < min_dist:
                        min_dist = dist
                        best_asset = filtered

    for kw_match in re.finditer(keyword_pattern, text_fixed, re.IGNORECASE):
        kw_center = (kw_match.start() + kw_match.end()) // 2
        start = max(0, kw_match.start() - 200)
        end = min(len(text_fixed), kw_match.end() + 300)
        window = text_fixed[start:end]

        for p_match in re.finditer(ASSET_PATTERN, window):
            p = p_match.group(0)
            if len(p) >= 4:
                filtered = filter_asset_no(p)
                if filtered != '未识别到编号':
                    if exclude_str and (filtered == exclude_str or filtered in exclude_str):
                        continue

                    p_center = start + p_match.start() + len(p)//2
                    dist = abs(p_center - kw_center)
                    if re.match(r'^(H|WSJ|NDJ|WJ|A|B)\d+', filtered, re.IGNORECASE):
                        dist -= 10000
                    if dist < min_dist:
                        min_dist = dist
                        best_asset = filtered
    return best_asset

