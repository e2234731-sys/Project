pdf_files_to_process = []
ignored_count = 0

for root, dirs, files in os.walk('.'):
    if ARCHIVE_BASE_DIR in root:
        ignored_count += sum(1 for f in files if f.lower().endswith('.pdf'))
        continue
    for filename in files:
        if filename.lower().endswith('.pdf'):
            pdf_files_to_process.append(os.path.join(root, filename))

print(f"📡 雷达扫描完毕：在当前非归档文件夹中共发现 {len(pdf_files_to_process)} 个待处理的 PDF 证书！")
