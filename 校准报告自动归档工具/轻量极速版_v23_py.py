def build_new_name(issuer, fields):
    if issuer == 'DN':
        parts = [fields['lab_name'], fields['asset_no'], fields['cal_date'], fields['issue_date'], fields['inst_name']]
    elif issuer == 'NEM':
        parts = [fields['serial_no'], fields['inst_name'], fields['cal_date'], fields['group']]
