def lookup_group(code):
    if not code or code in ('未知编号', '未识别到编号'): return '未知组别'
    code_upper = code.upper()
    for k, v in group_mapping.items():
        if k.upper() == code_upper: return v['group']
    return '未知组别'

def lookup_inst(code):
    if not code or code in ('未知编号', '未识别到编号'): return None
    code_upper = code.upper()
    for k, v in group_mapping.items():
        if k.upper() == code_upper and v.get('inst') and str(v['inst']).lower() not in ('nan', 'none', ''):
            return v['inst']
    for k, v in dn_mapping.items():
        if k.upper() == code_upper and v.get('inst') and str(v['inst']).lower() not in ('nan', 'none', ''):
            return v['inst']
    return None

def auto_match_from_registry(text_fixed, text_clean_fixed):
    asset_no = '未识别到编号'
    for asset in all_valid_assets:
        if len(asset) < 3: continue
        if re.match(r'^[A-Za-z]+\d+', asset) or len(asset) >= 4:
            if asset in text_fixed or asset in text_clean_fixed:
                asset_no = asset
                break

    inst_name = lookup_inst(asset_no)
    return asset_no, inst_name

