def find_value_by_keyword(text, keyword_pattern, value_pattern, search_range=4, col_tolerance_left=15, col_tolerance_right=60):
    lines = text.split('\n')
    for i, line in enumerate(lines):
        kw_match = re.search(keyword_pattern, line, re.IGNORECASE)
        if not kw_match: continue
        col_idx = kw_match.start()
        end_idx = kw_match.end()
        for j in range(i, min(i + search_range, len(lines))):
            target_line = lines[j]
            for val_match in re.finditer(value_pattern, target_line):
                v_start = val_match.start()
                val = val_match.group(0).strip()
                if not val: continue
                if j == i:
                    if v_start >= end_idx: return val
                else:
                    if (col_idx - col_tolerance_left) <= v_start <= (col_idx + col_tolerance_right):
                        return val
    return None

def extract_robust_date(text_clean_fixed, text_fixed, keyword_pattern_clean, keyword_pattern_raw):
    match = re.search(keyword_pattern_clean, text_clean_fixed, re.IGNORECASE)
    if match:
        start = max(0, match.start() - 80)
        end = min(len(text_clean_fixed), match.end() + 150)
        window = text_clean_fixed[start:end]
        dates = re.findall(r'\d{4}[-\.年/]\d{1,2}[-\.月/]\d{1,2}日?', window)
        if dates:
            return re.sub(r'[^\d]', '', dates[0])[:8]

    for match in re.finditer(keyword_pattern_raw, text_fixed, re.IGNORECASE):
        start = max(0, match.start() - 100)
        end = min(len(text_fixed), match.end() + 250)
        window = text_fixed[start:end]
        dates = re.findall(r'\d{4}\s*[-\.年/]\s*\d{1,2}\s*[-\.月/]\s*\d{1,2}\s*日?', window)
        if dates:
            return re.sub(r'[^\d]', '', dates[0])[:8]
    return None

def filter_asset_no(asset_no):
    if not asset_no or asset_no in ('未知编号', '未识别到编号'): return '未识别到编号'
    asset_no = asset_no.upper()

    asset_no = re.sub(r'(SERIALNO|ASSETNO|SERIAL|ASSET|MODEL|TYPE|NO|NAME)$', '', asset_no, flags=re.IGNORECASE)
    asset_no = re.sub(r'^WI(\d+)', r'WJ\1', asset_no)
    asset_no = re.sub(r'^HO(\d+)', r'H0\1', asset_no)
    asset_no = re.sub(r'^BES40(\d+)', r'H0\1', asset_no)
    asset_no = re.sub(r'^(DAFD|DAF|DAP|D)(H\d+|WSJ\d+|NDJ\d+|WJ\d+|A\d+|B\d+)', r'\2', asset_no)

    if not asset_no: return '未识别到编号'
    if re.match(r'^(JJF|JJG|GB|YY|JB|JC|SJ|T|SN|MT|PALL|ABSCIEX|WATERS|THERMO|AGILENT|SHIMADZU|DAF|ASSET|DATE|SERIAL|MODEL|DESCRIPTION|INFORMATION|CERTIFICATE|PAGE|EQUIPMENT)\b', asset_no):
        return '未识别到编号'
    if re.match(r'^L\d{4}$', asset_no):
        return '未识别到编号'

    return asset_no.replace('/', '-')

